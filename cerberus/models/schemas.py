"""
Pydantic Schemas for API Requests, Responses, and Agent Data Models.
"""

from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field


class SeverityEnum(str, Enum):
    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    INFO = "info"


class Finding(BaseModel):
    """Represents an individual issue or finding discovered by an agent."""

    id: Optional[str] = Field(default=None, description="Unique finding ID, e.g. SEC-001")
    severity: SeverityEnum = Field(description="Severity classification")
    category: str = Field(description="Finding category, e.g. injection, complexity, docstring")
    title: str = Field(description="Short, human-readable summary of the issue")
    message: str = Field(description="Detailed explanation of what was found")
    line: Optional[int] = Field(default=None, description="Line number in source code")
    column: Optional[int] = Field(default=None, description="Column offset in source code")
    code_snippet: Optional[str] = Field(default=None, description="Offending line or code block")
    explanation: Optional[str] = Field(default=None, description="Why this finding matters")
    recommendation: Optional[str] = Field(default=None, description="How to resolve the finding")
    suggestion: Optional[str] = Field(default=None, description="Concrete proposed code diff or replacement")
    cwe_id: Optional[str] = Field(default=None, description="Common Weakness Enumeration ID if applicable")
    cvss_score: Optional[float] = Field(default=None, description="CVSS 3.1 score between 0.0 and 10.0")
    exploitability: Optional[float] = Field(default=None, description="Estimated exploitability probability")
    false_positive_probability: Optional[float] = Field(default=0.02, description="Calculated FP probability")


class AgentResult(BaseModel):
    """Output generated by a single specialized review agent."""

    name: str = Field(description="Agent identifier: security, performance, quality, etc.")
    status: str = Field(default="completed", description="Status: completed, failed, or skipped")
    score: float = Field(default=100.0, ge=0.0, le=100.0, description="Agent-specific quality score")
    execution_time_ms: int = Field(default=0, description="Time taken to execute in milliseconds")
    findings: List[Finding] = Field(default_factory=list, description="Findings reported by this agent")
    error: Optional[str] = Field(default=None, description="Error message if agent execution failed")


class SeveritySummary(BaseModel):
    """Aggregated count of findings by severity level."""

    critical: int = 0
    high: int = 0
    medium: int = 0
    low: int = 0
    info: int = 0


class ReviewContext(BaseModel):
    """Contextual metadata about the source code being reviewed."""

    model_config = {"extra": "allow"}

    project_name: Optional[str] = None
    git_commit: Optional[str] = None
    file_path: Optional[str] = None
    git_branch: Optional[str] = None
    repo_owner: Optional[str] = None
    repo_name: Optional[str] = None
    custom: Optional[Dict[str, Any]] = None


class ReviewConfig(BaseModel):
    """Review-specific configuration overrides."""

    severity_threshold: Optional[str] = "medium"
    blocking_mode: Optional[bool] = False
    custom_rules: Optional[List[str]] = None


class CodeReviewRequest(BaseModel):
    """Payload to submit code for multi-agent review."""

    code: str = Field(..., max_length=500000, description="Source code text to review")
    language: Optional[str] = Field(default="python", description="Programming language (e.g. python, javascript, sql)")
    filename: Optional[str] = Field(default="snippet.py", description="Source filename for context")
    context: Optional[ReviewContext] = Field(default_factory=ReviewContext)
    agents: Optional[List[str]] = Field(default=None, description="Specific agents to run. Defaults to all active.")
    config: Optional[ReviewConfig] = Field(default_factory=ReviewConfig)
    webhook_url: Optional[str] = Field(default=None, description="Optional webhook URL to receive results")
    webhook_secret: Optional[str] = Field(default=None, description="Secret token for HMAC webhook verification")
    async_mode: Optional[bool] = Field(default=False, description="Whether to queue review asynchronously")


class ReviewResults(BaseModel):
    """Synthesized container for multi-agent findings, scores, and collaborative artifacts."""

    overall_score: float = Field(default=100.0, description="Overall weighted score")
    severity_summary: Dict[str, int] = Field(default_factory=dict, description="Summary counts by severity")
    agents: List[Dict[str, Any]] = Field(default_factory=list, description="Agent execution outputs")
    collaborative_consensus: Optional[Dict[str, Any]] = Field(default=None, description="Consensus agent details")
    unified_patch: Optional[str] = Field(default=None, description="AST-verified Git diff patch")
    trace: Optional[Dict[str, Any]] = Field(default=None, description="OpenTelemetry-compatible distributed trace data")

    def __getitem__(self, item: str) -> Any:
        return getattr(self, item)

    def get(self, item: str, default: Any = None) -> Any:
        return getattr(self, item, default)


class CodeReviewResponse(BaseModel):
    """Standard response containing review status and prioritized multi-agent findings."""

    review_id: str = Field(description="Unique review identifier, e.g. rev_8f7e6d5c4b3a2918")
    status: str = Field(description="processing, completed, failed")
    created_at: str
    completed_at: Optional[str] = None
    cache_hit: bool = False
    blocking: bool = False
    should_block: bool = False
    block_reason: Optional[str] = None
    overall_score: Optional[float] = None
    processing_time_ms: Optional[int] = None
    results: Optional[ReviewResults | Dict[str, Any]] = Field(
        default=None, description="Structured multi-agent review results and synthesized findings"
    )
    critical_issues: List[Finding] = Field(default_factory=list)
    warnings: List[Finding] = Field(default_factory=list)
    suggestions: List[Finding] = Field(default_factory=list)
    agents_scheduled: List[str] = Field(default_factory=list)
    webhook_url: Optional[str] = None
    _links: Optional[Dict[str, str]] = None
    summary: Optional[str] = None
    collaborative_consensus: Optional[Dict[str, Any]] = None
    unified_patch: Optional[str] = None
    trace_id: Optional[str] = Field(default=None, description="OpenTelemetry distributed trace ID")


class BatchReviewRequest(BaseModel):
    """Batch review submission for multiple files or snippets."""

    files: List[CodeReviewRequest]
    project_name: Optional[str] = None


class BatchReviewResponse(BaseModel):
    batch_id: str
    total_files: int
    reviews: List[CodeReviewResponse]


class ZipBase64ReviewRequest(BaseModel):
    """JSON payload for reviewing a base64-encoded ZIP archive."""

    zip_base64: str = Field(description="Base64-encoded ZIP archive content")
    project_name: Optional[str] = Field(default="uploaded_project")
    agents: Optional[List[str]] = Field(default=None, description="Optional specific agents to run")
    blocking: Optional[bool] = Field(default=False, description="Enable blocking mode")


class ZipFileReview(BaseModel):
    """Review metadata and findings summary for an individual file within a zip project."""

    file_path: str = Field(description="Relative file path within zip archive")
    filename: str = Field(description="Base filename")
    language: str = Field(description="Detected language")
    lines_of_code: int = Field(default=0, description="Total source lines")
    score: float = Field(default=100.0, description="Overall score for this file")
    status: str = Field(default="completed", description="Review status")
    review_id: str = Field(description="Individual review ID")
    critical_count: int = Field(default=0)
    high_count: int = Field(default=0)
    medium_count: int = Field(default=0)
    low_count: int = Field(default=0)
    findings_count: int = Field(default=0)
    review: CodeReviewResponse = Field(description="Full review response object")


class ZipReviewResponse(BaseModel):
    """Comprehensive synthesized review of an entire project ZIP archive."""

    project_name: str
    review_id: str = Field(description="Unique project review identifier")
    status: str = Field(default="completed", description="Overall project status")
    created_at: str
    completed_at: Optional[str] = None
    total_files_discovered: int
    reviewed_files_count: int
    skipped_files_count: int
    total_lines_of_code: int
    overall_project_score: float
    severity_summary: SeveritySummary
    language_distribution: Dict[str, int] = Field(default_factory=dict)
    file_reviews: List[ZipFileReview] = Field(default_factory=list)
    top_critical_findings: List[Finding] = Field(default_factory=list)
    processing_time_ms: int = 0
    collaborative_consensus: Optional[Dict[str, Any]] = None
    summary: Optional[str] = None


class FeedbackRequest(BaseModel):
    rating: int = Field(ge=1, le=5, description="Star rating from 1 to 5")
    is_helpful: bool = True
    false_positives: int = 0
    false_negatives: int = 0
    comments: Optional[str] = None


class FeedbackResponse(BaseModel):
    status: str = "success"
    message: str = "Feedback recorded successfully"


class ReviewStatusResponse(BaseModel):
    review_id: str
    status: str
    overall_score: Optional[float] = None
    created_at: str
    completed_at: Optional[str] = None
    should_block: bool = False
    block_reason: Optional[str] = None


class ReviewApproveRequest(BaseModel):
    reviewer: str = Field(default="engineer", description="Name or identifier of reviewer approving the PR")
    reason: Optional[str] = Field(default=None, description="Optional override rationale or note")
    override_blocking: bool = Field(
        default=True, description="Whether this approval overrides automated blocking gates"
    )


class ReviewApproveResponse(BaseModel):
    review_id: str
    status: str = "approved"
    approved_by: str
    approved_at: str
    override_applied: bool = True
    message: str = "Review manually approved for merge"


class AgentInfo(BaseModel):
    id: str
    name: str
    version: str
    purpose: str
    capabilities: List[str]
    status: str = "active"


class HealthResponse(BaseModel):
    status: str
    version: str
    timestamp: str
    database: str
    cache: str
    active_agents: List[str]
    uptime_seconds: float


class GitHubPRReviewComment(BaseModel):
    """Line-anchored GitHub Pull Request Review comment."""

    path: str
    line: int
    body: str


class GitHubPRReviewPayload(BaseModel):
    """Official GitHub Pull Request Review submission payload."""

    commit_id: Optional[str] = None
    event: str = Field(default="COMMENT", description="APPROVE, REQUEST_CHANGES, or COMMENT")
    body: str = Field(description="Markdown review summary body")
    comments: List[GitHubPRReviewComment] = Field(default_factory=list)


class GitHubPullRequestInfo(BaseModel):
    """Parsed GitHub Pull Request event context."""

    action: str
    pr_number: int
    repo_name: str
    repo_owner: str
    full_name: str
    title: str
    body: Optional[str] = None
    head_sha: Optional[str] = None
    head_ref: Optional[str] = None
    base_ref: Optional[str] = None
    diff_url: Optional[str] = None
    patch_url: Optional[str] = None
    html_url: Optional[str] = None


class GitHubWebhookReviewResult(BaseModel):
    """Result of automated GitHub pull_request.opened review."""

    status: str
    event: str
    action: str
    review_id: str
    pr_number: int
    repository: str
    overall_score: int
    verdict: str
    pr_review_action: str
    posted_to_github: bool
    github_review_payload: GitHubPRReviewPayload
    summary: str


class AstAnalysisMetadata(BaseModel):
    """Deep Tree-sitter AST structural metrics."""

    language: str
    parser_type: str = "tree_sitter"
    node_count: int = 0
    function_count: int = 0
    functions: List[str] = Field(default_factory=list)
    class_or_struct_count: int = 0
    classes_or_structs: List[str] = Field(default_factory=list)
    import_count: int = 0
    imports: List[str] = Field(default_factory=list)
    has_syntax_errors: bool = False
    syntax_errors: List[str] = Field(default_factory=list)
